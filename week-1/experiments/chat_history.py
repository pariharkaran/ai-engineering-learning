from langchain_core.messages import SystemMessage, HumanMessage, AIMessage
from src.llm import create_llm
from src.utils.display import (
    print_header, print_concept, print_divider, print_subheader, print_error, print_info, print_metric
)

def run_experiment():
    """
    Runs Experiment 3: Chat History.
    Demonstrates model statelessness and how conversation context is maintained.
    """
    print_header("Experiment 3: Chat History & State Isolation")

    # --- EDUCATIONAL CONTENT ---
    print_concept(
        "Is the LLM API Stateful or Stateless?",
        "LLMs are fundamentally stateless. Each API request you send to a model is processed in complete isolation. "
        "The model does not retain any memory of your previous questions or its own previous answers.\n\n"
        "  * Chat History ≠ Permanent Model Memory\n"
        "  * If you do not supply the previous conversation context on every new request, the model has no way of knowing what was previously discussed."
    )

    print_concept(
        "LangChain Message Types",
        "LangChain represents the conversation transcript using specific message classes:\n"
        "  1. SystemMessage: Sets the persona, behavior rules, instructions, or bounds for the AI. It is sent at the very beginning.\n"
        "  2. HumanMessage: Represents the message sent by the user.\n"
        "  3. AIMessage: Represents the response generated by the model."
    )

    print_concept(
        "The Cost of Chat History",
        "Because LLMs are stateless, to build a chat interface, the application must repeatedly send the entire "
        "conversation history (all past HumanMessages and AIMessages) along with the new user message. "
        "This means history consumes input tokens, and the cost of the conversation grows as it gets longer!"
    )

    # Establish the LLM instance
    llm = create_llm(temperature=0.0)

    # ==========================================
    # CASE A — NO HISTORY
    # ==========================================
    print_divider()
    print_subheader("Case A: Stateless Request (No History)")
    
    print_info("Step 1: Telling the model my name in isolation...")
    intro_message = [HumanMessage(content="Hello, my name is Karan. I am an engineer.")]
    try:
        res1 = llm.invoke(intro_message)
        print(f"  Human: {intro_message[0].content}")
        print(f"  AI: {res1.content}\n")
    except Exception as e:
        print_error(f"Failed intro message: {e}")
        return

    print_info("Step 2: Asking 'What is my name?' in a NEW isolated request...")
    question_no_history = [HumanMessage(content="What is my name?")]
    try:
        res2 = llm.invoke(question_no_history)
        print(f"  Human: {question_no_history[0].content}")
        
        # Remove Qwen reasoning tags for cleaner reading if present
        clean_content = res2.content
        if "<think>" in clean_content:
            clean_content = clean_content.split("</think>")[-1].strip()
            
        print(f"  AI: {clean_content}\n")
        print_info("Observation: Since no history was provided, the model has no idea who you are.")
    except Exception as e:
        print_error(f"Failed question without history: {e}")
        return

    # ==========================================
    # CASE B — WITH HISTORY
    # ==========================================
    print_divider()
    print_subheader("Case B: State Emulation (With Chat History)")

    print_info("Compiling conversation transcript manually using Message classes...")
    
    # We construct a transcript array representing the conversation
    messages_with_history = [
        SystemMessage(content="You are a helpful, concise AI assistant."),
        HumanMessage(content="Hello, my name is Karan. I am an engineer."),
        AIMessage(content="Nice to meet you, Karan! How can I help you today?"),
        HumanMessage(content="What is my name?")
    ]

    print("\nTranscript to be transmitted:")
    for msg in messages_with_history:
        print(f"  {type(msg).__name__}: {msg.content}")

    print_info("\nSending the full transcript to Groq...")
    try:
        res3 = llm.invoke(messages_with_history)
        
        clean_content = res3.content
        if "<think>" in clean_content:
            clean_content = clean_content.split("</think>")[-1].strip()
            
        print(f"\n  AI: {clean_content}\n")
        print_info("Observation: By providing the conversation history, the model has the context necessary to answer correctly.")
        
        # Display token costs for history transmission
        usage = getattr(res3, "usage_metadata", {})
        if usage:
            print_metric("Input Tokens (including history)", usage.get("input_tokens", "N/A"))
            print_metric("Output Tokens (new answer)", usage.get("output_tokens", "N/A"))
            print_metric("Total Tokens", usage.get("total_tokens", "N/A"))
            
    except Exception as e:
        print_error(f"Failed question with history: {e}")
