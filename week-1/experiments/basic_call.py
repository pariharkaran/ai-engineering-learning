from src.llm import create_llm
from src.config import DEFAULT_MODEL
from src.utils.display import (
    print_header, print_concept, print_metric, print_divider, print_subheader, print_error, print_info
)

def run_experiment():
    """
    Runs Experiment 1: Basic LLM Call.
    Demonstrates the simplest invocation lifecycle and prints core concepts.
    """
    print_header("Experiment 1: Basic LLM Call")

    # --- EDUCATIONAL CONTENT ---
    print_concept(
        "What is an LLM?",
        "A Large Language Model (LLM) is an AI model trained on vast amounts of text data to "
        "predict the next most likely token (word/sub-word) in a sequence. It generates text "
        "rather than retrieving facts from a database."
    )
    
    print_concept(
        "What is LangChain?",
        "LangChain is an open-source framework designed to simplify the construction of LLM-powered "
        "applications. It acts as an abstraction layer (an SDK middleware) that standardizes how "
        "we construct prompts, chain calls, and interact with different LLM providers."
    )
    
    print_concept(
        "What is Groq?",
        "Groq is an infrastructure provider (an API host) optimized for extreme speed. They run LLMs "
        "on their custom hardware called LPU (Language Processing Unit), enabling ultra-low latency response times."
    )
    
    print_concept(
        "What is ChatGroq?",
        "ChatGroq is the specific integration library class provided by LangChain (`langchain-groq`) "
        "that allows you to interface with Groq-hosted models using the standard LangChain interface."
    )

    print_concept(
        "Conceptual Flow & Relationships",
        "It is crucial to remember:\n"
        "  * Groq ≠ LangChain (Groq is the host/hardware; LangChain is the software framework)\n"
        "  * LangChain ≠ LLM (LangChain interacts with the LLM; it is not the AI model itself)\n"
        "  * ChatGroq = LangChain integration module for the Groq API"
    )

    print_concept(
        "What does invoke() do?",
        "The `.invoke()` method starts the request/response lifecycle. It takes a prompt or list of "
        "messages, serializes them into the format expected by the Groq API, transmits them over HTTP, "
        "receives the JSON response, and wraps it in a LangChain object."
    )

    print_concept(
        "What is AIMessage?",
        "LangChain represents the output of a Chat model as an `AIMessage` object. Unlike raw string outputs, "
        "it contains the generated text content (via `.content`) as well as rich usage metadata, finish reasons, "
        "and original API headers."
    )

    print_concept(
        "What are Tokens?",
        "Tokens are the basic building blocks of LLM text processing. Words are split into sub-word pieces "
        "called tokens (roughly 4 characters or 0.75 words per token). The API bills and tracks usage based on:\n"
        "  * Input Tokens (Prompt/Context sent to the model)\n"
        "  * Output Tokens (Response generated by the model)\n"
        "  * Total Tokens (Input + Output)"
    )

    print_divider()
    print_subheader("Executing LLM Request")

    # Define a simple prompt
    prompt = "Explain in one sentence what a token is in natural language processing."
    print(f"Prompt: '{prompt}'")
    print_info("Connecting to Groq...")

    try:
        # Create LLM using the factory
        llm = create_llm(temperature=0.0)
        
        # Call model
        response = llm.invoke(prompt)
        
        print_subheader("Results & Metadata")
        print(f"\nResponse:\n{response.content}\n")
        
        print_divider()
        
        # Model info
        print_metric("Model Name", DEFAULT_MODEL)
        
        # Token usage
        usage = getattr(response, "usage_metadata", None)
        if usage:
            print_metric("Input Tokens (Prompt)", usage.get("input_tokens", "N/A"))
            print_metric("Output Tokens (Response)", usage.get("output_tokens", "N/A"))
            print_metric("Total Tokens", usage.get("total_tokens", "N/A"))
        else:
            # Try parsing from response_metadata fallback
            resp_meta = getattr(response, "response_metadata", {})
            token_usage = resp_meta.get("token_usage", {})
            if token_usage:
                print_metric("Input Tokens (Prompt)", token_usage.get("prompt_tokens", "N/A"))
                print_metric("Output Tokens (Response)", token_usage.get("completion_tokens", "N/A"))
                print_metric("Total Tokens", token_usage.get("total_tokens", "N/A"))
            else:
                print_info("Token usage metadata is not available.")
                
    except Exception as e:
        print_error(f"Experiment execution failed: {e}")
